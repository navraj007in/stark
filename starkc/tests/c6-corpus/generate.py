def canonical_dimensions(dims) -> str:
    """A dimension tuple's canonical text. Deliberately not `repr` or `str` of the tuple: those are
    stable in practice but not contractually, and identity must not drift with a Python release."""
    parts = []
    for item in dims:
        if isinstance(item, (tuple, list)):
            parts.append("(" + ",".join(canonical_dimensions([x]) for x in item) + ")")
        elif isinstance(item, bool):
            parts.append("true" if item else "false")
        else:
            parts.append(str(item))
    return "|".join(parts)


def digest_for(template_id: str, dims, seed: str) -> str:
    material = f"{GENERATOR_VERSION}\x00{seed}\x00{template_id}\x00{canonical_dimensions(dims)}"
    return hashlib.sha256(material.encode("utf-8")).hexdigest()


def select(seed: str):
    """Every selected case, in deterministic order: templates sorted by ID, and within a template
    the dimension tuples ranked by digest and truncated to the budget."""
    chosen = []
    for template_id in sorted(template_registry.TEMPLATES):
        build, dimension_space = template_registry.TEMPLATES[template_id]
        ranked = sorted(
            ((digest_for(template_id, dims, seed), dims) for dims in dimension_space),
            key=lambda pair: pair[0],
        )
        if len(ranked) < 3:
            raise SystemExit(
                f"{template_id}: only {len(ranked)} dimension tuples — a template with fewer than "
                f"three instances is not a family, it is a case"
            )
        # R-01: a template whose dimension space IS the coverage claim is taken WHOLE. The budget
        # exists to bound cost where dimensions are interchangeable samples; for T16 each tuple is a
        # distinct normative trap category, so sampling deleted two of them while the corpus still
        # reported full coverage. Cost-bounding must never be able to remove a required observation.
        #
        # Otherwise: up to the budget, and a smaller space contributes all of it rather than being
        # padded with repeats. The §11.4 floor is checked globally, so a shortfall surfaces as "too
        # few cases" rather than as a silently thin template.
        take = (
            len(ranked)
            if template_id in template_registry.EXHAUSTIVE_TEMPLATES
            else min(PER_TEMPLATE_BUDGET, len(ranked))
        )
        for digest, dims in ranked[:take]:
            case = build(dims)
            case_id = f"gen__{template_id.lower()}__{digest[:8]}"
            chosen.append((case_id, template_id, digest, dims, case))
    chosen.sort(key=lambda entry: entry[0])
    # R-11: case IDs are a digest PREFIX, so a collision is improbable rather than impossible. Left
    # undetected it would be silent in the worst way: the second case overwrites the first's file and
    # the manifest carries two entries under one ID, so the corpus quietly loses a case and the
    # validator reports a duplicate long after the cause.
    seen: dict[str, str] = {}
    for case_id, template_id, digest, dims, _case in chosen:
        if case_id in seen:
            raise SystemExit(
                f"case ID collision: {case_id} produced by {seen[case_id]} and by "
                f"{template_id}/{canonical_dimensions(dims)} (digest {digest}). Widen the ID prefix "
                f"or change the dimension; do not let one case overwrite the other."
            )
        seen[case_id] = f"{template_id}/{canonical_dimensions(dims)}"
    return chosen


def enforce_bounds(case_id: str, case) -> None:
    """§11.8: the bounds are tested, not merely declared."""
    size = len(case.source.encode("utf-8"))
    if size > MAX_SOURCE_BYTES:
        raise SystemExit(f"{case_id}: {size} source bytes exceeds the {MAX_SOURCE_BYTES} bound")
    functions = case.source.count("\nfn ") + case.source.startswith("fn ")
    if functions > MAX_FUNCTIONS_PER_CASE:
        raise SystemExit(f"{case_id}: {functions} functions exceeds the {MAX_FUNCTIONS_PER_CASE} bound")
    # R-09: the loop bound is now READ. It was declared and never checked, which is the same as not
    # having one — §11.8 requires bounds to be set AND tested.
    if case.loop_iterations > MAX_LOOP_ITERATIONS:
        raise SystemExit(
            f"{case_id}: {case.loop_iterations} loop iterations exceeds the "
            f"{MAX_LOOP_ITERATIONS} bound"
        )
    if "/" in case_id or "\\" in case_id:
        raise SystemExit(f"{case_id}: a case ID must not contain a path separator")


def manifest_entry(case_id, template_id, digest, dims, case, seed) -> str:
    def lst(items):
        return "[" + ", ".join(f'"{item}"' for item in items) + "]"

    lines = [
        "[[case]]",
        f'case_id = "{case_id}"',
        'kind = "generated"',
        f'category = "{case.category}"',
        f"subcategories = {lst(case.subcategories)}",
        f'sources = ["cases/generated/{case_id}.stark"]',
        'package_graph = "single-file"',
        f'expected_outcome = "{case.expected_outcome}"',
    ]
    if case.expected_trap_category:
        lines.append(f'expected_trap_category = "{case.expected_trap_category}"')
    lines += [
        'required_engines = ["hir", "mir", "native-debug"]',
        'required_targets = ["aarch64-apple-darwin", "x86_64-unknown-linux-gnu"]',
        f"normative_rules = {lst(case.normative_rules)}",
        f'generator_seed = "{seed}"',
        f'generator_version = "{GENERATOR_VERSION}"',
        f'template_id = "{template_id}"',
    ]
    if case.expected_stdout:
        lines.append(f"expected_stdout = {lst(case.expected_stdout)}")
    if case.drop_protocol:
        lines.append("drop_protocol = true")
        lines.append(f"expected_drop_log = {lst(case.expected_drop_log)}")
    return "\n".join(lines) + "\n"


GENERATED_MANIFEST_HEADER = """# WP-C6.5 GENERATED cases (§11) — written by `generate.py --write`. Do not hand-edit: the next
# regeneration overwrites it, and the corpus lock hashes both this file and the generator.
#
# Hand-authored cases live in `manifest.toml`. The split keeps a regeneration from ever touching a
# case a person wrote, and keeps a person from editing an expectation the generator derived.
#
# Each case's `expected_stdout` / `expected_drop_log` comes from the TEMPLATE's semantic model, not
# from running an engine: the corpus claims the engines agree with the specification, and an
# expectation read back from one of them could only show they agree with each other.
"""


def write_metamorphic(out_root: pathlib.Path) -> list:
    """§13 pairs. Both members of a group are written as ordinary cases carrying family/group
    metadata, so the replay harness runs them like any other case AND the metamorphic harness can
    pair them up. Nothing about a pair is special-cased in the replay — a pair whose members did not
    also individually agree across engines would be meaningless."""
    pairs_dir = out_root / "metamorphic"
    if pairs_dir.exists():
        shutil.rmtree(pairs_dir)
    pairs_dir.mkdir(parents=True)
    def lst(items):
        return "[" + ", ".join(f'"{item}"' for item in items) + "]"

    entries = []
    for group in metamorphic_registry.groups():
        members = (
            (("base", group.base_files), ("transformed", group.transformed_files))
            if group.kind != "source"
            else (("base", group.base), ("transformed", group.transformed))
        )
        for role, payload in members:
            case_id = f"meta__{group.family_id.lower()}_{group.group_id}_{role}"

            if group.kind != "source":
                # A package member is a TREE. Each role gets its own directory, which is also what
                # makes M08 meaningful: the two members are separate physical roots on disk before
                # the harness stages them to two more.
                # Nested under `metamorphic/pkg/` rather than `metamorphic/` because
                # `stage_package` takes the first THREE path components as the tree root to copy
                # (matching `cases/<kind>/<case>`). At `metamorphic/<case>/app` that made `app`
                # itself the root, so staging silently dropped its sibling packages and resolution
                # then failed on a dependency path that "does not exist".
                member_dir = pairs_dir / "pkg" / case_id
                for relative, contents in sorted(payload.items()):
                    target = member_dir / relative
                    target.parent.mkdir(parents=True, exist_ok=True)
                    target.write_text(contents, encoding="utf-8", newline="\n")
                sources = [
                    f"metamorphic/pkg/{case_id}/{relative}"
                    for relative in sorted(payload)
                    if relative.endswith(".stark")
                ]
                package_root = f"metamorphic/pkg/{case_id}/{group.package_root}"
            else:
                (pairs_dir / f"{case_id}.stark").write_text(
                    payload, encoding="utf-8", newline="\n"
                )
                sources = [f"metamorphic/{case_id}.stark"]
                package_root = None

            body = [
                "[[case]]",
                f'case_id = "{case_id}"',
                'kind = "handwritten"',
                f'category = "{group.category}"',
                # R-13: the FAMILY lives in `metamorphic_family`; `subcategories` is for matrix ROW
                # ids. Writing `M01` here made ten family ids count as covered rows, which is how
                # R-07's coverage number was inflated — and nothing caught it, because nothing
                # checked that a cited row exists.
                f"subcategories = {lst(group.subcategories)}",
                f"sources = {lst(sources)}",
                f'package_graph = "{group.package_graph}"',
                f'expected_outcome = "{"trap" if group.expected_trap else "completion"}"',
                'required_engines = ["hir", "mir", "native-debug"]',
                'required_targets = ["aarch64-apple-darwin", "x86_64-unknown-linux-gnu"]',
                "normative_rules = ["
                + ", ".join(f'"{rule}"' for rule in group.normative_rules)
                + "]",
                f'metamorphic_family = "{group.family_id}"',
                f'metamorphic_group = "{group.family_id}-{group.group_id}"',
                f'metamorphic_role = "{role}"',
                f'metamorphic_kind = "{group.kind}"',
                f'metamorphic_precondition = "{group.precondition}"',
                "expected_stdout = ["
                + ", ".join(f'"{line}"' for line in group.expected_stdout)
                + "]",
            ]
            if package_root:
                body.append(f'package_root = "{package_root}"')
            if group.expected_drop_log:
                body.append("drop_protocol = true")
                body.append(f"expected_drop_log = {lst(group.expected_drop_log)}")
            if group.expected_trap:
                body.append(f'expected_trap_category = "{group.expected_trap}"')
            if group.pin_canonical_symbols:
                body.append("metamorphic_pin_canonical_symbols = true")
            if group.pin_logical_provenance:
                body.append("metamorphic_pin_logical_provenance = true")
            entries.append((case_id, "\n".join(body) + "\n"))
    return entries


def write_generated(out_root: pathlib.Path, seed: str) -> None:
    cases_dir = out_root / "cases" / "generated"
    if cases_dir.exists():
        shutil.rmtree(cases_dir)
    cases_dir.mkdir(parents=True)
    entries = []
    for case_id, template_id, digest, dims, case in select(seed):
        enforce_bounds(case_id, case)
        (cases_dir / f"{case_id}.stark").write_text(case.source, encoding="utf-8", newline="\n")
        entries.append(manifest_entry(case_id, template_id, digest, dims, case, seed))
    if len(entries) < GENERATED_FLOOR:
        raise SystemExit(
            f"only {len(entries)} generated cases; §11.4's floor is {GENERATED_FLOOR}. Lowering the "
            f"floor needs a recorded rationale, not a quiet edit"
        )
    # Metamorphic members are cases too, and share the generated manifest because both are written
    # by `--write`. Sorted together so the file obeys the manifest's ascending-case_id rule.
    numbered = [(entry.split('case_id = "')[1].split('"')[0], entry) for entry in entries]
    numbered.extend(write_metamorphic(out_root))
    numbered.sort(key=lambda pair: pair[0])
    text = GENERATED_MANIFEST_HEADER + "\n" + "\n".join(entry for _, entry in numbered)
    (out_root / "generated.manifest.toml").write_text(text, encoding="utf-8", newline="\n")


def check_generated() -> int:
    """§11.9: regenerate into a temp directory and byte-compare against what is checked in."""
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        scratch = pathlib.Path(tmp)
        write_generated(scratch, DEFAULT_SEED)
        drift = []
        checked_in = sorted((ROOT / "cases" / "generated").glob("*.stark")) + sorted(
            (ROOT / "metamorphic").glob("*.stark")
        )
        regenerated = sorted((scratch / "cases" / "generated").glob("*.stark")) + sorted(
            (scratch / "metamorphic").glob("*.stark")
        )
        if [p.name for p in checked_in] != [p.name for p in regenerated]:
            only_in = {p.name for p in checked_in} ^ {p.name for p in regenerated}
            drift.append(f"case set differs: {sorted(only_in)}")
        for path in regenerated:
            mirror = ROOT / path.relative_to(scratch)
            if not mirror.exists() or mirror.read_bytes() != path.read_bytes():
                drift.append(f"{path.name} differs")
        if (ROOT / "generated.manifest.toml").read_bytes() != (
            scratch / "generated.manifest.toml"
        ).read_bytes():
            drift.append("generated.manifest.toml differs")
        if drift:
            print("generated corpus is stale:\n  " + "\n  ".join(drift), file=sys.stderr)
            return 1
    print("generated corpus is current")
    return 0


def list_templates() -> int:
    print(f"generator_version {GENERATOR_VERSION}, default_seed {DEFAULT_SEED}")
    print(f"per-template budget {PER_TEMPLATE_BUDGET}, floor {GENERATED_FLOOR}")
    for template_id in sorted(template_registry.TEMPLATES):
        build, space = template_registry.TEMPLATES[template_id]
        summary = (build.__doc__ or "").strip().splitlines()[0]
        print(f"  {template_id}  {len(space):3d} tuples  {summary}")
    print("not in the registry (recorded, not stubbed):")
    for template_id, why in sorted(template_registry.MISSING_TEMPLATES.items()):
        print(f"  {template_id}  {why}")
    families = {}
    for group in metamorphic_registry.groups():
        families.setdefault(group.family_id, []).append(group.group_id)
    total_groups = sum(len(ids) for ids in families.values())
    print(f"metamorphic: {len(families)} families, {total_groups} groups, {total_groups * 2} members")
    for family, group_ids in sorted(families.items()):
        print(f"  {family}  groups {', '.join(sorted(group_ids))}")
    print("metamorphic families absent (recorded, not approximated):")
    for family, why in sorted(metamorphic_registry.MISSING_FAMILIES.items()):
        print(f"  {family}  {why}")
    return 0


