def self_test_guards() -> int:
    """Negative controls for the two guards §17 added (R-09, R-11).

    A guard that has never refused anything is a guard nobody has watched work. This mode forces
    each failure deliberately and requires the generator to reject it; `c6_corpus_generator.rs` runs
    it and asserts a non-zero exit with the expected reason.
    """
    failures = []

    # R-11: two dimension tuples forced to the same case ID.
    original_digest = globals()["digest_for"]
    globals()["digest_for"] = lambda template_id, dims, seed: "c0111de" + "d" * 57
    try:
        select(DEFAULT_SEED)
        failures.append("collision was NOT detected")
    except SystemExit as refusal:
        if "case ID collision" not in str(refusal):
            failures.append(f"collision refused for the wrong reason: {refusal}")
    finally:
        globals()["digest_for"] = original_digest

    # R-09: a case declaring more loop iterations than the bound allows.
    over = template_registry.Case(
        source="fn main() {}\n",
        category="control-transfer",
        subcategories=(),
        normative_rules=("EXEC-CFLOW-001",),
        loop_iterations=MAX_LOOP_ITERATIONS + 1,
    )
    try:
        enforce_bounds("probe", over)
        failures.append("the loop bound was NOT enforced")
    except SystemExit as refusal:
        if "loop iterations exceeds" not in str(refusal):
            failures.append(f"loop bound refused for the wrong reason: {refusal}")

    # R-04/R-05: the kind-aware metamorphic guards. Driven through the REAL
    # `validate_package_pair` rather than a copy of its rules — a self-test that reimplements the
    # guard proves the copy works.
    diamond = metamorphic_registry.DIAMOND_WORKSPACE
    reordered = metamorphic_registry.reorder_dependencies(diamond, "app/starkpkg.json")
    edited = dict(diamond)
    edited["base/src/main.stark"] = edited["base/src/main.stark"].replace("v * 2", "v * 3")
    narrowed = dict(diamond)
    narrowed["app/starkpkg.json"] = metamorphic_registry._manifest("app", ["left"])
    reordered_and_edited = dict(reordered)
    reordered_and_edited["base/src/main.stark"] = edited["base/src/main.stark"]

    for what, kind, base, transformed, wanted in [
        (
            "a relocation pair whose trees differ",
            "relocation", diamond, edited, "must keep every logical file",
        ),
        (
            "a reorder that also edits a source file",
            "dependency-reorder", diamond, reordered_and_edited, "only MANIFESTS may differ",
        ),
        (
            "a reorder that changes the dependency SET",
            "dependency-reorder", diamond, narrowed, "changed the dependency SET",
        ),
        (
            "a reorder that reordered nothing",
            "dependency-reorder", diamond, dict(diamond), "reordered nothing",
        ),
        (
            "an unknown transformation kind",
            "teleportation", diamond, reordered, "unknown package transformation kind",
        ),
    ]:
        try:
            metamorphic_registry.validate_package_pair("MX", "probe", kind, base, transformed)
            failures.append(f"{what} was ACCEPTED")
        except AssertionError as refusal:
            if wanted not in str(refusal):
                failures.append(f"{what} refused for the wrong reason: {refusal}")

    if failures:
        for failure in failures:
            print(f"guard self-test FAILED: {failure}", file=sys.stderr)
        return 1
    print(
        "guard self-tests pass: collision, loop bound, and five metamorphic package-pair rules all "
        "refuse"
    )
    return 0


def main() -> int:
    argv = sys.argv[1:]
    if argv[:1] == ["--self-test-guards"]:
        return self_test_guards()
    if argv[:1] == ["--list-templates"]:
        return list_templates()
    if argv[:1] == ["--write"]:
        write_generated(ROOT, DEFAULT_SEED)
        print(f"wrote cases/generated/ and generated.manifest.toml (seed {DEFAULT_SEED})")
        return 0
    if argv[:1] == ["--check"]:
        return check_generated()
    if len(argv) == 4 and argv[0] == "--seed" and argv[2] == "--out":
        out = pathlib.Path(argv[3])
        out.mkdir(parents=True, exist_ok=True)
        write_generated(out, argv[1])
        print(f"wrote {out} (seed {argv[1]})")
        return 0
    if argv != ["--lock"]:
        print(__doc__)
        return 2
    lock_path = ROOT / "corpus.lock"
    # `generator_sha256` hashes this script, so writing the lock changes nothing about the script
    # itself — no fixed point to iterate.
    lock_path.write_text(build_lock(), encoding="utf-8", newline="\n")
    print(f"wrote {lock_path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
