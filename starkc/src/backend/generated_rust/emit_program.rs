//! Top-level program emission: assembles the generated crate's `src/main.rs`. WP-C5.2d lifts
//! WP-C5.2b/c's single-function restriction -- every body in `program.bodies` (already a
//! self-contained, transitively-reachable set per `lower_program`'s own doc comment: "the entry
//! `main` plus every transitively-called supported function") is emitted as its own Rust `fn`.
//! The entry instance (`mangle::ENTRY_SYMBOL`, matching `mir::interp::run_program`'s own lookup,
//! per §5.2's "no backend semantic reconstruction") is still special-cased as Rust's literal
//! `fn main()` with the version-check prologue prepended; every other body goes through
//! `emit_bodies::emit_function` with its symbol's sanitized name. Indirect calls through a
//! function value remain WP-C5.4c.

use super::{
    emit_bodies, emit_projections, emit_provider, emit_types, linkage, mangle, BackendDiagnostic,
};
use crate::mir::{MirBody, MirProgram, MirTy};
use stark_runtime::version::BuildVersions;

pub struct GeneratedSource {
    pub main_rs: String,
}

pub fn emit(
    program: &MirProgram,
    versions: &BuildVersions,
    layout: &crate::layout::TargetLayout,
) -> Result<GeneratedSource, BackendDiagnostic> {
    // WP-C5.4a §6: the linkage preflight is the deterministic refusal boundary. It validates the
    // body set (unique/sorted canonical symbols, unique generated names, every referenced instance
    // resolving to exactly one body with matching identity) BEFORE any source is assembled, so no
    // internally-inconsistent or out-of-subset program reaches rustc.
    let _linkage = linkage::build(program)?;

    let entry = program
        .bodies
        .iter()
        .find(|b| b.instance.symbol == mangle::ENTRY_SYMBOL)
        .ok_or_else(|| {
            BackendDiagnostic::Unsupported(format!(
                "no `{}` instance in verified MIR -- every C5 program must have a monomorphised \
                 entry point",
                mangle::ENTRY_SYMBOL
            ))
        })?;
    // Rust's `fn main()` takes no parameters and returns `()`; this is an entry-specific
    // constraint on the wrapper below, not a general property of `emit_bodies`, which stays
    // reusable for an arbitrary-signature ordinary function.
    if !entry.params.is_empty() {
        return Err(BackendDiagnostic::Unsupported(
            "the entry instance must take no parameters to become Rust's `fn main()`".to_string(),
        ));
    }

    let mut main_rs = String::new();
    main_rs.push_str("// GENERATED by the STARK native backend (WP-C5.2d). Do not edit.\n");
    // WP-C6.1g-c: `unconditional_panic`/`arithmetic_overflow` are deny-by-default rustc lints that
    // fire when rustc can CONST-EVALUATE an out-of-bounds index or an overflowing arithmetic op.
    // STARK's semantics make those RUNTIME traps (via the emitted bounds/overflow checks that call
    // `stark_runtime::trap::abort`), NOT compile-time rejections. The dispatch loop happened to hide
    // the constants from rustc; the linearised labelled-block emission lets rustc see them, so these
    // lints must be allowed or a statically-known trapping program fails to BUILD instead of
    // trapping at run time (the three-engine contract requires it to run and trap).
    main_rs.push_str("#![allow(dead_code, unused, unconditional_panic, arithmetic_overflow)]\n\n");

    // WP-C5.3a: §6.3's "one Rust definition per reachable concrete nominal instance", emitted
    // before every function so declaration order never depends on use order.
    main_rs.push_str(&emit_types::emit_nominal_definitions(program)?);

    // WP-C5.3d-0: the generated projection helpers, collected from the bodies below. Emitted
    // before them so the module is in scope, and so the ONE place unsafe appears in a generated
    // program is visible at the top of the file rather than buried.
    let projections = emit_projections::collect(program, layout)?;
    main_rs.push_str(&emit_projections::emit(&projections, &program.types)?);

    // WP-C5.4c (§7.5): one aborting sentinel per distinct function-pointer signature, emitted
    // before ordinary bodies so a default-initialised `FnPtr` local (Copy, never slot-backed) has
    // a valid Rust default that aborts rather than silently calling a real function.
    main_rs.push_str(&emit_types::emit_fn_sentinels(program)?);

    // A10 (CD-200): one `extern "C"` block for every provider function the program calls, emitted
    // before the bodies that call them and deduplicated by symbol, so the declaration set does not
    // depend on body iteration order.
    main_rs.push_str(&emit_provider::emit_extern_declarations(program)?);

    for body in &program.bodies {
        main_rs.push_str(&format!("// STARK instance: {}\n", body.instance.symbol));
        if body.instance.symbol == mangle::ENTRY_SYMBOL {
            main_rs.push_str(&emit_entry_fn(
                body,
                versions,
                &program.files,
                &program.types,
                layout,
                &program.provider_calls,
            )?);
        } else {
            let name = mangle::function_name_for_symbol(&body.instance.symbol);
            main_rs.push_str(&emit_bodies::emit_function(
                body,
                &name,
                &program.files,
                &program.types,
                layout,
                &program.provider_calls,
            )?);
        }
        main_rs.push('\n');
    }

    Ok(GeneratedSource { main_rs })
}

fn emit_entry_fn(
    entry: &MirBody,
    versions: &BuildVersions,
    files: &[std::sync::Arc<crate::source::SourceFile>],
    types: &crate::mir::TypeContext,
    layout: &crate::layout::TargetLayout,
    provider_calls: &[crate::mir::ValidatedProviderCall],
) -> Result<String, BackendDiagnostic> {
    let mut out = String::new();
    let mut prologue = String::new();
    prologue.push_str("    let __stark_build_versions = ");
    prologue.push_str(&emit_build_versions_literal(versions));
    prologue.push_str(";\n");
    prologue.push_str(
        "    if let Err(mismatch) = stark_runtime::version::check(&__stark_build_versions) {\n",
    );
    prologue.push_str("        eprintln!(\"stark-runtime version mismatch: generated for runtime {}, linked against {}\", mismatch.expected_runtime_version, mismatch.actual_runtime_version);\n");
    prologue.push_str("        std::process::exit(1);\n");
    prologue.push_str("    }\n");

    if matches!(entry.ret, MirTy::Unit) {
        // The common case is unchanged: a `Unit` entry IS Rust's `fn main()`.
        let block = emit_bodies::emit_block_body(entry, files, types, layout, provider_calls)?;
        out.push_str("fn main() {\n");
        out.push_str(&prologue);
        out.push_str("    ");
        out.push_str(&block);
        out.push_str("}\n");
        return Ok(out);
    }

    // CD-150 CE3: PROC-MAIN-001 admits `Int32`, `Result<Unit, String>` and `Result<Int32, String>`
    // as well, and PROC-EXIT-001 says what each means. The entry is emitted as an ORDINARY function
    // with its real return type, and `fn main()` applies the exit contract to its result — which
    // keeps the mapping in one readable place instead of threading a status through the body.
    out.push_str(&emit_bodies::emit_function(
        entry,
        "__stark_entry",
        files,
        types,
        layout,
        provider_calls,
    )?);
    let entry_file = files
        .first()
        .map(|f| f.name.clone())
        .unwrap_or_else(|| "<entry>".to_string());
    // Provenance for the range trap is the ENTRY FILE at 1:1 (MIR amendment A7): the contract is
    // violated by the entry's result, not by an expression, and all three engines report this same
    // location rather than three plausible ones.
    let range_trap = format!(
        "stark_runtime::trap::abort(stark_runtime::trap::TrapCategory::InvalidExitStatus, {}, 1, 1)",
        rust_str_lit(&entry_file)
    );
    let exit_with_status = format!(
        "            if __stark_status < 0 || __stark_status > 255 {{\n                {range_trap};\n            }}\n            std::process::exit(__stark_status);\n"
    );

    out.push_str("fn main() {\n");
    out.push_str(&prologue);
    match &entry.ret {
        MirTy::Int32 => {
            out.push_str("    let __stark_status: i32 = __stark_entry() as i32;\n");
            out.push_str(&exit_with_status.replace("            ", "    "));
        }
        MirTy::Enum(crate::mir::EnumRef::CoreResult, args) => {
            let result_ty = emit_types::nominal_type_name(&entry.ret).ok_or_else(|| {
                BackendDiagnostic::Unsupported(
                    "entry returns a Result whose generated type has no name".to_string(),
                )
            })?;
            let ok_is_unit = matches!(args.first(), Some(MirTy::Unit));
            out.push_str("    match __stark_entry() {\n");
            if ok_is_unit {
                // `Ok(Unit)` returns status 0 (PROC-EXIT-001).
                out.push_str(&format!(
                    "        {result_ty}::{}(_) => {{}}\n",
                    emit_types::variant_name(0)
                ));
            } else {
                out.push_str(&format!(
                    "        {result_ty}::{}(__stark_ok) => {{\n            let __stark_status: i32 = __stark_ok as i32;\n{exit_with_status}        }}\n",
                    emit_types::variant_name(0)
                ));
            }
            // `Err(message)` writes the message plus LF to stderr and returns status 1.
            out.push_str(&format!(
                "        {result_ty}::{}(__stark_error) => {{\n            stark_runtime::output::flush_stdout();\n            eprint!(\"{{}}\\n\", __stark_error);\n            std::process::exit(1);\n        }}\n",
                emit_types::variant_name(1)
            ));
            out.push_str("    }\n");
        }
        other => {
            return Err(BackendDiagnostic::Unsupported(format!(
                "entry returns {other:?}, which PROC-MAIN-001 does not admit"
            )));
        }
    }
    out.push_str("}\n");
    Ok(out)
}

fn emit_build_versions_literal(versions: &BuildVersions) -> String {
    format!(
        "stark_runtime::version::BuildVersions {{ \
         compiler_version: {}.to_string(), \
         mir_version: {}.to_string(), \
         mir_runtime_surface: {}.to_string(), \
         runtime_version: {}.to_string(), \
         backend_version: {}.to_string(), \
         rustc_version: {}.to_string(), \
         target_triple: {}.to_string(), \
         profile: {}.to_string() }}",
        rust_str_lit(&versions.compiler_version),
        rust_str_lit(&versions.mir_version),
        rust_str_lit(&versions.mir_runtime_surface),
        rust_str_lit(&versions.runtime_version),
        rust_str_lit(&versions.backend_version),
        rust_str_lit(&versions.rustc_version),
        rust_str_lit(&versions.target_triple),
        rust_str_lit(&versions.profile),
    )
}

/// A Rust string-literal token for an arbitrary host-reported string (rustc version, target
/// triple). These come from `rustc -vV`, not user source, but are escaped defensively rather
/// than trusted verbatim.
fn rust_str_lit(s: &str) -> String {
    format!("\"{}\"", s.escape_default())
}
